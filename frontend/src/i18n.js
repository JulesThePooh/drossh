let current = 'en';

// detectLang : langue sauvegardée > langue système (si dispo) > anglais.
export function detectLang(saved) {
  if (saved && translations[saved]) return saved;
  const sys = (navigator.language || 'en').slice(0, 2).toLowerCase();
  if (translations[sys]) return sys;
  return 'en';
}
export function setLang(code) { if (translations[code]) current = code; }
export function getLang() { return current; }

// t : traduit une clé + substitue {vars}. Fallback : anglais, puis la clé elle-même.
export function t(key, vars) {
  const dict = translations[current] || translations.en;
  let s = dict[key] != null ? dict[key] : (translations.en[key] != null ? translations.en[key] : key);
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

// applyStaticI18n : applique les traductions sur le HTML statique via les attributs data-i18n*.
export function applyStaticI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((e) => { e.textContent = t(e.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-html]').forEach((e) => { e.innerHTML = t(e.getAttribute('data-i18n-html')); });
  root.querySelectorAll('[data-i18n-ph]').forEach((e) => { e.setAttribute('placeholder', t(e.getAttribute('data-i18n-ph'))); });
  root.querySelectorAll('[data-i18n-title]').forEach((e) => { e.setAttribute('title', t(e.getAttribute('data-i18n-title'))); });
  root.querySelectorAll('[data-i18n-aria]').forEach((e) => { e.setAttribute('aria-label', t(e.getAttribute('data-i18n-aria'))); });
  document.documentElement.setAttribute('lang', current);
}
